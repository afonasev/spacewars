#!/usr/bin/env python3
"""Compile the retained web document into immutable native map content."""
import hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
raw=(ROOT/'docs/moss-highland/visual-options/web-source.json').read_bytes();d=json.loads(raw)
assert (d['width'],d['depth'],d['cellSize'])==(128,128,2)
# The central level-one component is the playable plateau. Raised peripheral
# rock shoulders remain solid authored geology, not extra gameplay platforms.
center={(32,32)};todo=list(center)
while todo:
 x,z=todo.pop()
 for q in [(x-1,z),(x+1,z),(x,z-1),(x,z+1)]:
  if q not in center and 0<=q[0]<64 and 0<=q[1]<64 and d['cells'][q[1]*64+q[0]]['level']==1:center.add(q);todo.append(q)
def rects(key):
 used=set();out=[]
 for z in range(64):
  for x in range(64):
   k=key(x,z,d['cells'][z*64+x])
   if k is None or (x,z) in used:continue
   end=x+1
   while end<64 and (end,z) not in used and key(end,z,d['cells'][z*64+end])==k:end+=1
   bottom=z+1
   while bottom<64 and all((i,bottom) not in used and key(i,bottom,d['cells'][bottom*64+i])==k for i in range(x,end)):bottom+=1
   used.update((i,j) for j in range(z,bottom) for i in range(x,end));out.append((x*2-64,z*2-64,end*2-64,bottom*2-64,k))
 return out
plateau=rects(lambda x,z,c:1 if (x,z) in center else None)
ridges=rects(lambda x,z,c:c['level'] if c['level']>0 and (x,z) not in center else None)
patches=rects(lambda x,z,c:c['material'])
lines=['// Generated by tools/compile_moss_highland.py from the retained source.','namespace Spacewars.Simulation { internal static class MossHighlandLayout {', 'public const string SourceRevision="7d0acb8d078451eaf0ed166a6f8b6d748925abf8";',f'public const string SourceSha256="{hashlib.sha256(raw).hexdigest()}";']
for name,rows in [('Plateau',plateau),('Ridges',ridges)]:
 lines.append('public static readonly double[,] '+name+'={');lines+=['{'+','.join(str(v) for v in r)+'},' for r in rows];lines.append('};')
# Presentation unions adjacent source cells at each authored height. Independent
# rectangular erosion would produce visible stripes through a connected ridge.
contours=[]
for level in (1,2,3):
 occupied={(x,z) for z in range(64) for x in range(64) if d['cells'][z*64+x]['level']>=level and (x,z) not in center}
 edges={}
 for x,z in sorted(occupied):
  for neighbor,start,end in [((x,z-1),(x,z),(x+1,z)),((x+1,z),(x+1,z),(x+1,z+1)),((x,z+1),(x+1,z+1),(x,z+1)),((x-1,z),(x,z+1),(x,z))]:
   if neighbor not in occupied:edges.setdefault(start,[]).append(end)
 while edges:
  start=min(edges);cur=start;ring=[start]
  while True:
   nxt=edges[cur].pop(0)
   if not edges[cur]:del edges[cur]
   if nxt==start:break
   ring.append(nxt);cur=nxt
  # Retain every turn, omit collinear grid vertices without changing the footprint.
  turns=[]
  for i,b in enumerate(ring):
   aa=ring[i-1];cc=ring[(i+1)%len(ring)]
   if (b[0]-aa[0])*(cc[1]-b[1])!=(b[1]-aa[1])*(cc[0]-b[0]):turns.append((b[0]*2-64,b[1]*2-64))
  contours.append((turns,level))
lines.append('public static readonly NavObstacle[] Geology={')
for ring,level in contours:
 lines.append('new NavObstacle(new NavPolygon(new NavPoint[]{'+','.join('new NavPoint('+str(x)+','+str(z)+')' for x,z in ring)+'}),'+'0'+','+str(level)+'),')
lines.append('};')
lines.append('public static readonly MossMaterialPatch[] Materials={');lines+=['new MossMaterialPatch('+','.join(str(v) for v in r[:4])+',"'+r[4]+'"),' for r in patches];lines+=['};','public static readonly double[,] Sites={']
lines+=['{'+','.join(str(v) for v in [s['x'],s['z'],s.get('rotationDeg',0)])+'},' for s in d['sites']];lines+=['};','}}']
(ROOT/'unity/Assets/Spacewars/Simulation/MossHighlandLayout.cs').write_text('\n'.join(lines)+'\n')
(ROOT/'docs/moss-highland/source.json').write_text(json.dumps({'revision':'7d0acb8d078451eaf0ed166a6f8b6d748925abf8','sha256':hashlib.sha256(raw).hexdigest(),'width':128,'depth':128,'level_height':1,'ramp_slope_degrees':22,'plateau_cells':len(center),'plateau_rectangles':len(plateau),'ridge_rectangles':len(ridges),'materials':len(patches),'sites':d['sites'],'ramps':d['ramps']},ensure_ascii=False,indent=2)+'\n')
