#!/usr/bin/env python3
"""Export exact approved GLB triangles grouped by fixed/yaw/pitch motion roots.
No renderer, nav footprint or hand-authored hitbox is substituted for mesh geometry.
"""
from pathlib import Path
import base64,hashlib,struct,zlib
from building_model_geometry import GLB,matrix,multiply,point,IDENTITY
ROOT=Path(__file__).resolve().parents[1]
def export():
 source=ROOT/'unity/Assets/Spacewars/Content/StyleA/sentry-turret.glb';g=GLB(source);d=g.data
 groups={n:[[],[]] for n in ['modelRoot','turretYaw','weaponPitch']}
 def walk(i,m=IDENTITY,group='modelRoot'):
  node=d['nodes'][i];name=node.get('name','')
  if name in groups:group=name;m=IDENTITY
  else:m=multiply(m,matrix(node))
  if 'mesh' in node:
   verts,indices=groups[group]
   for primitive in d['meshes'][node['mesh']]['primitives']:
    offset=len(verts);verts.extend(point(m,v) for v in g.accessor(primitive['attributes']['POSITION']));indices.extend(offset+int(x[0]) for x in g.accessor(primitive['indices']))
  for ch in node.get('children',[]):walk(ch,m,group)
 for i in d['scenes'][d.get('scene',0)]['nodes']:walk(i)
 code=['// Generated by tools/export_sentry_geometry.py from the approved GLB, exact articulated surfaces.','namespace Spacewars.Simulation { internal static class SentryCombatData {',f' internal const string SourceHash="{hashlib.sha256(source.read_bytes()).hexdigest()}";']
 for name,(vertices,indices) in groups.items():
  raw=struct.pack('<if',1,0)+struct.pack('<iiffffii',0,0,0,0,0,0,len(vertices),len(indices))+b''.join(struct.pack('<fff',*v) for v in vertices)+struct.pack('<'+'i'*len(indices),*indices)
  compressor=zlib.compressobj(9,zlib.DEFLATED,-15);encoded=base64.b64encode(compressor.compress(raw)+compressor.flush()).decode()
  code.append(' internal const string '+name+' =\n'+' +\n'.join('  "'+encoded[i:i+120]+'"' for i in range(0,len(encoded),120))+';')
 code.append('} }');target=ROOT/'unity/Assets/Spacewars/Simulation/SentryCombatData.cs';target.write_text('\n'.join(code)+'\n')
 print('Sentry surfaces exported:',{n:len(v[1])//3 for n,v in groups.items()})
if __name__=='__main__':export()
