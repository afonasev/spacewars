#!/usr/bin/env python3
"""Reproduce native Basalt Crown content from the retained, immutable web document."""
import hashlib,json,subprocess
from pathlib import Path
REV='7d0acb8d078451eaf0ed166a6f8b6d748925abf8'
SOURCE='maps/custom/koltsevaya-tsitadel.spacewars-map.json'
root=Path(__file__).resolve().parents[1]
raw=subprocess.check_output(['git','show',f'{REV}:{SOURCE}'],cwd=root)
d=json.loads(raw);cols=d['width']//2;rows=d['depth']//2
# Map coordinates are authored content; grid is the source's two-metre invariant.
def rects(key):
 used=set();out=[]
 for z in range(rows):
  for x in range(cols):
   k=key(d['cells'][z*cols+x])
   if k is None or (x,z) in used:continue
   e=x+1
   while e<cols and (e,z) not in used and key(d['cells'][z*cols+e])==k:e+=1
   b=z+1
   while b<rows and all((i,b) not in used and key(d['cells'][b*cols+i])==k for i in range(x,e)):b+=1
   used.update((i,j) for j in range(z,b) for i in range(x,e))
   out.append((-d['width']/2+x*2,-d['depth']/2+z*2,-d['width']/2+e*2,-d['depth']/2+b*2,k))
 return out
def number(n):return format(n,'.9g')
plateau=rects(lambda c:1 if c['level']==1 else None)
ridges=rects(lambda c:c['level'] if c['level']>=2 else None)
# Retain material regions separately; navigation does not use texture names.
patches=rects(lambda c:c['material'])
lines=['// Generated by tools/compile_basalt_crown.py; do not edit authored arrays.','namespace Spacewars.Simulation {','internal static class BasaltCrownLayout {',f' public const string SourceRevision="{REV}";',f' public const string SourceSha256="{hashlib.sha256(raw).hexdigest()}";']
for name,items in [('Plateau',plateau),('Ridges',ridges)]:
 lines.append(f' public static readonly double[,] {name}={{')
 lines.extend('  {'+','.join(number(n) for n in r)+'},' for r in items);lines.append(' };')
# Source-painted material plan, kept as content IDs rather than renderer state.
lines.append(' public static readonly BasaltMaterialPatch[] Materials={')
lines.extend('  new BasaltMaterialPatch('+','.join(number(n) for n in r[:4])+',"'+r[4]+'"),' for r in patches);lines+=[' };','}}']
(root/'unity/Assets/Spacewars/Simulation/BasaltCrownLayout.cs').write_text('\n'.join(lines)+'\n')
(root/'docs/basalt-crown/source.json').write_text(json.dumps({'revision':REV,'path':SOURCE,'sha256':hashlib.sha256(raw).hexdigest(),'name':d['name'],'width':d['width'],'depth':d['depth'],'levelHeight':1,'rampSlopeDegrees':22,'sites':d['sites'],'ramps':d['ramps'],'plateauRectangles':len(plateau),'ridgeRectangles':len(ridges),'materialPatches':len(patches)},ensure_ascii=False,indent=2)+'\n')
