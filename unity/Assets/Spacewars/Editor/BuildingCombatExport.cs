using System;
using System.IO;
using System.IO.Compression;
using System.Linq;
using System.Text;
using System.Collections.Generic;
using System.Security.Cryptography;
using UnityEditor;
using UnityEngine;
namespace Spacewars.Editor
{
 // Offline copy of authored prefab surfaces. Simulation consumes immutable numbers,
 // never scene objects, renderer visibility, Unity colliders or navigation footprints.
 public static class BuildingCombatExport
 {
  static readonly string[] Keys={"headquarters-a","factory-armored","mine-armored","outpost-b","research-scanner","research-scanner-upgraded","refinery","refineryUpgraded","hangar"};
  [Serializable] sealed class Row {public string key,prefabHash,surfaceHash;public int parts,triangles;}
  [Serializable] sealed class Manifest {public string version;public float doorTravel;public Row[] models;}
  static string Hash(byte[] b){using var sha=SHA256.Create();return BitConverter.ToString(sha.ComputeHash(b)).Replace("-","").ToLowerInvariant();}
  public static void Export(){Generate(true);}
  public static void Validate(){Generate(false);}
  static void Generate(bool write)
  {
   var rows=new List<Row>();var constants=new StringBuilder();var all=new MemoryStream();
   var factory=Spacewars.Presentation.FactoryModelProfile.Load();factory.Validate();
   var apron=Spacewars.Presentation.EnvironmentArtProfile.Load();
   using(var w=new BinaryWriter(all,Encoding.UTF8,true)){w.Write(factory.doorTravel);w.Write(apron.apronHeight);}
   foreach(string key in Keys)
   {
    string path="Assets/Spacewars/Content/Resources/StyleA/"+key+".prefab";
    var prefab=AssetDatabase.LoadAssetAtPath<GameObject>(path);if(!prefab)throw new Exception("Missing combat source "+key);
    var filters=prefab.GetComponentsInChildren<MeshFilter>(true).Where(f=>f.sharedMesh&&f.GetComponent<MeshRenderer>()).ToArray();
    // Bake the authored mine-only world yaw into the immutable surface, matching PlayableWorld.Facing.
    var modelYaw=key=="mine-armored"?Quaternion.Euler(0,Spacewars.Presentation.ArmoredMineProfile.Load().facingYawDegrees,0):Quaternion.identity;
    float roller=prefab.GetComponentsInChildren<Transform>(true).FirstOrDefault(t=>t.name=="gateRollerStore")?.localPosition.y??0;
    var bytes=new MemoryStream();int triangles=0;
    using(var w=new BinaryWriter(bytes,Encoding.UTF8,true))
    {
     w.Write(filters.Length);w.Write(roller);
     foreach(var f in filters)
     {
      int motion=0,index=0;Transform pivot=null;
      for(var t=f.transform;t&&t!=prefab.transform;t=t.parent)
      {
       if(t.name.StartsWith("doorSection")&&int.TryParse(t.name.Substring(11),out index)){motion=1;pivot=t;break;}
       if(t.name.StartsWith("roofPetal")&&int.TryParse(t.name.Substring(9),out index)){motion=2;pivot=t;break;}
       if(t.name=="irisBacking"){motion=3;pivot=t;break;}
       if(t.name=="launchPlatform"){motion=4;pivot=t;break;}
      }
      var axis=pivot?prefab.transform.InverseTransformVector(pivot.parent.TransformVector(Vector3.up)):Vector3.zero;
      w.Write(motion);w.Write(index);w.Write(pivot?pivot.localPosition.y:0);w.Write(axis.x);w.Write(axis.y);w.Write(axis.z);
      var verts=f.sharedMesh.vertices;var indices=f.sharedMesh.triangles;w.Write(verts.Length);w.Write(indices.Length);triangles+=indices.Length/3;
      foreach(var v in verts){var at=modelYaw*prefab.transform.InverseTransformPoint(f.transform.TransformPoint(v));w.Write(at.x);w.Write(at.y);w.Write(at.z);}
      foreach(int i in indices)w.Write(i);
     }
    }
    var raw=bytes.ToArray();using(var w=new BinaryWriter(all,Encoding.UTF8,true)){w.Write(key);w.Write(raw.Length);w.Write(raw);}
    var compressed=new MemoryStream();using(var zip=new DeflateStream(compressed,System.IO.Compression.CompressionLevel.Optimal,true))zip.Write(raw,0,raw.Length);
    string encoded=Convert.ToBase64String(compressed.ToArray());constants.Append("    case \"").Append(key).Append("\": return ");
    for(int i=0;i<encoded.Length;i+=16000){if(i>0)constants.Append(" +\n      ");constants.Append('"').Append(encoded.Substring(i,Math.Min(16000,encoded.Length-i))).Append('"');}constants.Append(";\n");
    rows.Add(new Row{key=key,prefabHash=Hash(File.ReadAllBytes(path)),surfaceHash=Hash(raw),parts=filters.Length,triangles=triangles});
   }
   string version="building-combat-surface-v1:"+Hash(all.ToArray());
   string code="// Generated by Spacewars.Editor.BuildingCombatExport.Export; authored geometry, not balance tuning.\nnamespace Spacewars.Simulation\n{\n internal static class BuildingCombatData\n {\n  internal const string Version=\""+version+"\";\n  internal const double DoorTravel="+factory.doorTravel.ToString("R",System.Globalization.CultureInfo.InvariantCulture)+";\n  internal const double ApronLift="+apron.apronHeight.ToString("R",System.Globalization.CultureInfo.InvariantCulture)+";\n  internal static string Encoded(string key){switch(key){\n"+constants+"    default: throw new System.ArgumentException(\"Unknown building combat geometry: \"+key);\n  }}\n }\n}\n";
   const string dataPath="Assets/Spacewars/Simulation/BuildingCombatData.cs";
   if(write)File.WriteAllText(dataPath,code);else if(File.ReadAllText(dataPath)!=code)throw new Exception("Building combat surfaces are stale; run BuildingCombatExport.Export");
   string folder=Path.GetFullPath("../design/building-combat-geometry");string manifest=JsonUtility.ToJson(new Manifest{version=version,doorTravel=factory.doorTravel,models=rows.ToArray()},true)+"\n";
   if(write){Directory.CreateDirectory(folder);File.WriteAllText(Path.Combine(folder,"manifest.json"),manifest);AssetDatabase.Refresh();Debug.Log("BUILDING_COMBAT_EXPORT_PASS "+version);}
   else if(File.ReadAllText(Path.Combine(folder,"manifest.json"))!=manifest)throw new Exception("Building combat provenance is stale; run BuildingCombatExport.Export");
  }
 }
}
